#!/usr/bin/env python3
"""Generate public, synthetic libjpeg RGB oracles. Requires Pillow==12.3.0.

No JLISwift encoder/decoder is used. Fixtures run without Python or libjpeg.
Run from any directory; writes ../JLISwiftTests/ChromaReferenceFixtures.swift.
"""
from pathlib import Path
import base64
import hashlib
import io
from PIL import Image, features
import PIL

out = Path(__file__).resolve().parents[1] / 'JLISwiftTests/ChromaReferenceFixtures.swift'
cases = [(w,h,s,p) for s in (1,2) for w,h in ((64,18),(63,19),(7,5),(3,5),(4,3),(1,1)) for p in (False,)]
cases += [(63,19,s,True) for s in (1,2)] + [(63,19,0,False)]
colors = [(240,30,25),(15,215,65),(25,50,235),(230,220,35),(20,200,225),(210,25,190)]
lines = ['// Generated by Tests/FixtureGenerators/generate_chroma_fixtures.py.',
         f'// Pillow {PIL.__version__}; libjpeg-turbo {features.version("libjpeg_turbo")}.',
         '// Synthetic source only; independently encoded/decoded, no JLISwift involvement.',
         'enum ChromaReferenceFixtures {',
         '    struct Fixture: Sendable {',
         '        let name: String', '        let width: Int', '        let height: Int',
         '        let jpeg: String', '        let rgb: String', '    }',
         '    static let all: [Fixture] = [']
for w,h,s,progressive in cases:
    pixels = bytearray()
    for y in range(h):
        for x in range(w):
            color = colors[(x * 6 // w + (3 if y >= h//2 else 0)) % 6]
            pixels += bytes(max(0,min(255,c+(x*3+y*7)%13-6)) for c in color)
    source = Image.frombytes('RGB',(w,h),bytes(pixels))
    stream = io.BytesIO()
    source.save(stream,format='JPEG',quality=87,subsampling=s,progressive=progressive,optimize=False)
    jpeg = stream.getvalue()
    with Image.open(io.BytesIO(jpeg)) as reference:
        rgb = reference.convert('RGB').tobytes()
    name=f'{"progressive" if progressive else "baseline"}_{["444","422","420"][s]}_{w}x{h}'
    lines += [f'        // {name}: JPEG SHA256 {hashlib.sha256(jpeg).hexdigest()}',
              f'        // RGB SHA256 {hashlib.sha256(rgb).hexdigest()}',
              f'        Fixture(name: "{name}", width: {w}, height: {h},',
              f'                jpeg: "{base64.b64encode(jpeg).decode()}",',
              f'                rgb: "{base64.b64encode(rgb).decode()}"),']
lines += ['    ]', '}','']
out.write_text('\n'.join(lines))
print(f'Generated {len(cases)} synthetic RGB oracle fixtures ({out.stat().st_size} bytes)')
