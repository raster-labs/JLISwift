    static var count: Int { definition.utf8CodeUnitCount / 2 }
    static func byte(at index: Int) -> UInt8 {
        precondition(index >= 0 && index < count)
        return definition.withUTF8Buffer { bytes in
            func digit(_ c: UInt8) -> UInt8 { c <= 57 ? c - 48 : c - 87 }
            return digit(bytes[index * 2]) * 16 + digit(bytes[index * 2 + 1])
        }
    }
    static let data: [UInt8] = {
        var result = [UInt8](repeating: 0, count: count)
        for index in 0..<count { result[index] = byte(at: index) }
        return result
    }()
    static func matches(_ input: [UInt8]?) -> Bool {
        guard let input, input.count == count else { return false }
        for index in 0..<count where input[index] != byte(at: index) { return false }
        return true
    }
}
